function generateContent(chapterNumber) {
  const seed = chapterNumber % fallbackContent.length
  const count = 4 + (chapterNumber % 5)
  const result = []
  for (let i = 0; i < count; i++) {
    result.push(fallbackContent[(seed + i) % fallbackContent.length])
  }
  return result
}

export function getChapters(novelId) {
  if (customChapters[novelId]) return customChapters[novelId]

  const novel = getNovelById(novelId)
  if (novel?.chapters) return novel.chapters.map((ch) => ({ ...ch }))

  return []
}

export function getChapter(novelId, chapterId) {
  const chapters = getChapters(novelId)
  const meta = chapters.find((c) => c.id === chapterId) || null
  if (!meta) return null

  let content
  if (customContent[chapterId]) {
    content = customContent[chapterId]
  } else if (typeof customContent[novelId] === 'object' && customContent[novelId][chapterId]) {
    content = customContent[novelId][chapterId]
  } else {
    content = generateContent(meta.number || 1)
  }

  return { ...meta, content }
}

export function getChapterById(novelId, chapterId) {
  return getChapter(novelId, chapterId)
}
